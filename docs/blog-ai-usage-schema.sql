-- =============================================================
-- blog_ai_usage · 后台 AI 调用审计表
--   记录非对话类的 AI 调用（生成文章标题、生成摘要等），与 blog_ai_sessions /
--   blog_ai_messages 分开：不挂会话、不进用户对话列表，只做用量统计与审计追溯。
--
--   生成时文章可能尚未落库（用户在「信息弹窗」里点 AI 按钮，此时文章还没
--   createPost），故 ref_id 允许 NULL；可由后端在文章提交后回填。
--
-- 执行方式：psql 直连 postgres 库后运行本脚本
-- 执行后  ：需重跑 jOOQ codegen  `mvn generate-sources`
--           使新表生成到 com.syt.blog.jooq
-- =============================================================

CREATE TABLE IF NOT EXISTS blog_ai_usage (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       INTEGER,                            -- 登录用户；游客场景留空（本功能需登录，故非空）
    user_ip       VARCHAR(45),                        -- 调用方 IP，便于异常追溯
    type          VARCHAR(20) NOT NULL,               -- title=生成标题 / summary=生成摘要（可扩展）
    ref_type      VARCHAR(20),                        -- 关联对象类型：post / comment 等
    ref_id        BIGINT,                             -- 关联对象 id（如 postId）；生成时尚未落库则 NULL
    input_text    TEXT,                               -- 发给模型的输入（正文截断后），便于复盘
    output_text   TEXT,                               -- 模型返回结果（生成的标题/摘要）
    tokens        INTEGER NOT NULL DEFAULT 0,         -- 本次消耗 token
    model         VARCHAR(64),                        -- 使用的模型名
    status        SMALLINT NOT NULL DEFAULT 1,        -- 0=失败 1=成功（与 blog_ai_messages 一致）
    error_message VARCHAR(500),                      -- 失败原因（status=0 时填）
    created_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE  blog_ai_usage IS '后台AI调用审计表（生成标题/摘要等非对话类调用）';
COMMENT ON COLUMN blog_ai_usage.type      IS '调用类型：title=生成标题 summary=生成摘要';
COMMENT ON COLUMN blog_ai_usage.ref_type  IS '关联对象类型：post / comment 等';
COMMENT ON COLUMN blog_ai_usage.ref_id    IS '关联对象 id（如 postId），生成时尚未落库则 NULL';
COMMENT ON COLUMN blog_ai_usage.status   IS '0=失败 1=成功';
COMMENT ON COLUMN blog_ai_usage.input_text IS '发给模型的输入（正文截断后）';

-- 按用户拉用量统计（最近在前）
CREATE INDEX IF NOT EXISTS idx_ai_usage_user_created
    ON blog_ai_usage (user_id, created_at DESC);

-- 按类型统计（如：摘要调用总次数 / token）
CREATE INDEX IF NOT EXISTS idx_ai_usage_type_created
    ON blog_ai_usage (type, created_at DESC);
