-- =============================================================
-- 私信功能建表：blog_conversations（会话）+ blog_messages（消息）
-- 说明:
--   会话按「用户对」聚合，user_a_id < user_b_id 归一化，唯一约束防重建；
--   消息逐条落库，会话冗余 last_message_* 与 *_unread_count 加速列表渲染。
--   每条消息同时物化一条 type='message' 站内通知（复用 createNotification）。
--   PostgreSQL 语法（容器 pgvector-db，库 postgres）。
--   建表后需重新构建以触发 jOOQ 代码生成。
--   与 blog_follows 同风格：外键 ON DELETE CASCADE、created_at 默认当前时间、
--   约束命名 uq_/ck_/idx_、会话表挂 trg_*_updated_at 触发器。
-- =============================================================

-- 1. 会话表（每对用户一行）
CREATE TABLE IF NOT EXISTS blog_conversations (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_a_id        INTEGER NOT NULL REFERENCES blog_users(id) ON DELETE CASCADE,
  user_b_id        INTEGER NOT NULL REFERENCES blog_users(id) ON DELETE CASCADE,
  -- 最后一条消息（纯冗余，应用层维护；不设外键以避免与 blog_messages 循环引用）
  last_message_id  BIGINT DEFAULT NULL,
  last_message_at  TIMESTAMP DEFAULT NULL,
  a_unread_count   INTEGER NOT NULL DEFAULT 0,
  b_unread_count   INTEGER NOT NULL DEFAULT 0,
  a_hidden         SMALLINT NOT NULL DEFAULT 0,
  b_hidden         SMALLINT NOT NULL DEFAULT 0,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_conversations_pair      UNIQUE (user_a_id, user_b_id),
  -- user_a_id 恒小于 user_b_id：同时禁止自聊并保证同一对用户只有一行
  CONSTRAINT ck_conversations_order     CHECK (user_a_id < user_b_id),
  CONSTRAINT ck_conversations_a_unread  CHECK (a_unread_count >= 0),
  CONSTRAINT ck_conversations_b_unread  CHECK (b_unread_count >= 0)
);
CREATE INDEX IF NOT EXISTS idx_conversations_last_at ON blog_conversations(last_message_at DESC);

COMMENT ON TABLE  blog_conversations               IS '私信会话：每对用户一行，user_a_id < user_b_id';
COMMENT ON COLUMN blog_conversations.user_a_id     IS '会话双方中 ID 较小者';
COMMENT ON COLUMN blog_conversations.user_b_id     IS '会话双方中 ID 较大者';
COMMENT ON COLUMN blog_conversations.last_message_id IS '最后一条消息ID（冗余，加速列表渲染，应用层维护）';
COMMENT ON COLUMN blog_conversations.last_message_at IS '最后消息时间（会话列表排序用）';
COMMENT ON COLUMN blog_conversations.a_unread_count IS 'user_a 未读消息数（冗余计数）';
COMMENT ON COLUMN blog_conversations.b_unread_count IS 'user_b 未读消息数（冗余计数）';
COMMENT ON COLUMN blog_conversations.a_hidden      IS 'user_a 是否已删除该会话（仅对自己隐藏）';
COMMENT ON COLUMN blog_conversations.b_hidden      IS 'user_b 是否已删除该会话';

-- 2. 消息表（会话内逐条）
CREATE TABLE IF NOT EXISTS blog_messages (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id  BIGINT NOT NULL REFERENCES blog_conversations(id) ON DELETE CASCADE,
  sender_id        INTEGER NOT NULL REFERENCES blog_users(id) ON DELETE CASCADE,
  receiver_id      INTEGER NOT NULL REFERENCES blog_users(id) ON DELETE CASCADE,
  content          TEXT NOT NULL,
  is_read          SMALLINT NOT NULL DEFAULT 0,
  read_at          TIMESTAMP DEFAULT NULL,
  created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_messages_not_self CHECK (sender_id <> receiver_id)
);
CREATE INDEX IF NOT EXISTS idx_messages_conv_time   ON blog_messages(conversation_id, created_at);
CREATE INDEX IF NOT EXISTS idx_messages_recv_unread ON blog_messages(receiver_id, is_read);

COMMENT ON TABLE  blog_messages              IS '私信消息：会话内逐条，接收者视角 is_read';
COMMENT ON COLUMN blog_messages.conversation_id IS '所属会话';
COMMENT ON COLUMN blog_messages.sender_id     IS '发送者';
COMMENT ON COLUMN blog_messages.receiver_id   IS '接收者';
COMMENT ON COLUMN blog_messages.content       IS '正文（纯文本，上限 1000 字）';
COMMENT ON COLUMN blog_messages.is_read       IS '接收者是否已读：0=未读 1=已读';
COMMENT ON COLUMN blog_messages.read_at       IS '接收者已读时间';

-- 3. 会话表 updated_at 触发器（对齐 blog_ai_sessions 惯例；jOOQ 应用层亦会维护，此处兜底）
CREATE TRIGGER trg_conversations_updated_at
  BEFORE UPDATE ON blog_conversations
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();
