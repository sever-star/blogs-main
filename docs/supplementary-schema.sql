-- -------------------------------------------------------------
-- P0-1  启用 pgvector 扩展（RAG 向量检索）
-- -------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS vector;

-- -------------------------------------------------------------
-- P0-1  文章向量分块表
--   embedding 维度按实际 embedding 模型定，先按 1024，
--   实测后可用 ALTER ... TYPE vector(N) 调整
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS blog_post_embeddings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id      INTEGER NOT NULL REFERENCES blog_posts(id) ON DELETE CASCADE,
    chunk_index  INTEGER NOT NULL DEFAULT 0,
    content      TEXT    NOT NULL,
    embedding    vector(1024),
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 向量相似度检索索引（HNSW，适合近邻检索）
CREATE INDEX IF NOT EXISTS idx_post_embeddings_embedding
    ON blog_post_embeddings
    USING hnsw (embedding vector_cosine_ops);

-- 按文章取回所有 chunk 的索引
CREATE INDEX IF NOT EXISTS idx_post_embeddings_post
    ON blog_post_embeddings (post_id);

-- -------------------------------------------------------------
-- P0-2  AI 消息增加「引用来源」字段（RAG 回答带出处）
--   结构：[{ "post_id": 12, "title": "...", "url": "/posts/12", "score": 0.82 }]
-- -------------------------------------------------------------
ALTER TABLE blog_ai_messages
    ADD COLUMN IF NOT EXISTS sources JSON;

-- -------------------------------------------------------------
-- P0-3  文章增加「向量化状态」字段
--   0=待处理(PENDING) 1=已完成(READY) 2=失败(FAILED，可重试)
-- -------------------------------------------------------------
ALTER TABLE blog_posts
    ADD COLUMN IF NOT EXISTS embedding_status SMALLINT NOT NULL DEFAULT 0;

-- -------------------------------------------------------------
-- blog_posts.status 默认值：经 pg_dump 核对，实际库结构本就是 DEFAULT 0（草稿）
--   （0=草稿 1=已发布 2=已下架），无需 ALTER。
--   保留下面这行作为幂等兜底，防止误改后未察觉。
-- -------------------------------------------------------------
ALTER TABLE blog_posts ALTER COLUMN status SET DEFAULT 0;

-- -------------------------------------------------------------
-- P1-1  用户表增加角色字段（区分博主/管理员与读者）
--   ADMIN=博主/管理员  USER=普通读者
-- -------------------------------------------------------------
ALTER TABLE blog_users
    ADD COLUMN IF NOT EXISTS role VARCHAR(20) NOT NULL DEFAULT 'USER';

-- -------------------------------------------------------------
-- P1-2  统一日志表 user_id 类型（BIGINT -> INTEGER，对齐 blog_users.id）
--   注意：该两表为日志流水，无外键约束，改动安全；
--   若已存在超 INT 范围的脏数据会导致失败（正常不会）
-- -------------------------------------------------------------
ALTER TABLE blog_login_logs     ALTER COLUMN user_id TYPE INTEGER USING user_id::INTEGER;
ALTER TABLE blog_operation_logs ALTER COLUMN user_id TYPE INTEGER USING user_id::INTEGER;

-- -------------------------------------------------------------
-- 文章审核字段（新增文章 → 管理员审核 → 发布 流程）
--   review_status 按 enum-dictionary.md 审核状态约定：
--     0=待审核 1=通过 2=拒绝
--   reviewer_id   审核人（blog_users.id），未审核为 NULL
--   reviewed_at   审核时间，未审核为 NULL
-- -------------------------------------------------------------
ALTER TABLE blog_posts
    ADD COLUMN IF NOT EXISTS review_status SMALLINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS reviewer_id   INTEGER,
    ADD COLUMN IF NOT EXISTS reviewed_at   TIMESTAMP;

-- ★ 一次性回填（仅首次执行时运行，功能上线后勿重复执行）：
--   存量文章视为「已通过」审核，避免上线审核过滤后旧文章全部消失。
--   重复执行会把新投稿的「待审核」文章误标为已通过，切勿重跑本段。
UPDATE blog_posts SET review_status = 1 WHERE review_status = 0;

-- -------------------------------------------------------------
-- P3-1  文章列表查询复合索引（已发布 + 置顶 + 时间倒序）
-- -------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_posts_status_top_created
    ON blog_posts (status, is_top, created_at DESC);

-- -------------------------------------------------------------
-- P3-2  评论列表复合索引（按文章 + 审核状态）
-- -------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_comments_post_status
    ON blog_comments (post_id, status);

